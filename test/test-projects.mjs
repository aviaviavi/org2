import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { compileCorpus, compileCorpusIncremental } from '../dist/corpusCompile.js';
import { queryNodeActions } from '../dist/nodeActions.js';
import { createProjectNote, updateProjectNote, listProjectNotes } from '../dist/project.js';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'org2-projects-'));
const thread = '11111111-1111-4111-8111-111111111111';
try {
  fs.writeFileSync(path.join(root, 'org2.json'), JSON.stringify({roam: {nodesDir: 'knowledge'}}));
  const preview = createProjectNote(root, {title: 'Launch', color: 'purple'});
  assert.equal(fs.existsSync(preview.project.file), false);
  assert.match(preview.project.relativePath, /^knowledge\/projects\//);
  const created = createProjectNote(root, {title: 'Launch', color: 'purple', id: preview.project.id, file: preview.project.relativePath, apply: true});
  assert.equal(created.content, preview.content);
  assert.match(created.project.brief, /\* TODO Next action/);
  assert.doesNotMatch(created.project.brief, /PROJECT_COLOR|:PROPERTIES:/);
  assert.equal(listProjectNotes(root).projects.length, 1);
  const actions = queryNodeActions(compileCorpus([created.project.file], {rootDir: root}), {object: `id:${created.project.id}`});
  assert.equal(actions.counts.open, 1);
  assert.equal(actions.open[0].title, 'Next action');
  const cacheFile = path.join(root, '.cache.json');
  compileCorpusIncremental([created.project.file], {rootDir: root, cacheFile});
  const oldCache = JSON.parse(fs.readFileSync(cacheFile, 'utf8'));
  oldCache.schemaVersion = 'org2-incremental-corpus-cache/v4';
  fs.writeFileSync(cacheFile, JSON.stringify(oldCache));
  fs.unlinkSync(cacheFile + '.v8');
  const rebuilt = compileCorpusIncremental([created.project.file], {rootDir: root, cacheFile});
  assert.equal(rebuilt.indexState.parsedFiles, 1);
  assert.equal(queryNodeActions(rebuilt, {object: `id:${created.project.id}`}).counts.open, 1);
  const scopedFile = path.join(root, 'scoped.org');
  fs.writeFileSync(scopedFile, '* Scope\n:PROPERTIES:\n:ID: scoped-project\n:ORG2_ENTITY_TYPE: project\n:END:\n** TODO Inside\n* TODO Outside\n');
  const scoped = queryNodeActions(compileCorpus([scopedFile], {rootDir: root}), {object: 'id:scoped-project'});
  assert.deepEqual(scoped.open.map(x => x.title), ['Inside']);
  const update = updateProjectNote(root, created.project.id, {threadID: thread});
  assert.deepEqual(listProjectNotes(root).projects[0].threadIDs, []);
  const applied = updateProjectNote(root, created.project.id, {threadID: thread, expectedRevision: created.project.revision, apply: true});
  assert.equal(update.content, applied.content);
  assert.deepEqual(applied.project.threadIDs, [thread]);
  assert.throws(() => updateProjectNote(root, created.project.id, {color: 'red', expectedRevision: created.project.revision, apply: true}), /revision|changed|conflict/i);
  updateProjectNote(root, created.project.id, {threadID: thread, remove: true, apply: true});
  assert.deepEqual(listProjectNotes(root).projects[0].threadIDs, []);
  const body = ':PROPERTIES:\r\n:ID: existing-note-id\r\n:OWNER: Me\r\n:END:\r\n#+TITLE: Old\r\n* TODO Keep this action\r\nBody with [[id:another][link]].\r\n#+begin_src org\r\n#+PROJECT_COLOR: red\r\n#+end_src\r\n';
  fs.writeFileSync(path.join(root, 'existing.org'), body);
  const adopted = createProjectNote(root, {title: 'Existing', file: 'existing.org', adopt: true, apply: true});
  assert.equal(adopted.project.id, 'existing-note-id');
  assert.ok(adopted.content.endsWith(body.slice(body.indexOf('* TODO'))));
  assert.match(adopted.content, /:OWNER: Me/);
  assert.match(adopted.project.brief, /PROJECT_COLOR: red/);
  fs.writeFileSync(path.join(root, 'without-id.org'), '* TODO Preserve this\n');
  const adoptPreview = createProjectNote(root, {title: 'No ID', file: 'without-id.org', adopt: true});
  const adoptApplied = createProjectNote(root, {title: 'No ID', file: 'without-id.org', adopt: true, id: adoptPreview.project.id, expectedRevision: adoptPreview.baseRevision, apply: true});
  assert.equal(adoptApplied.content, adoptPreview.content);
  fs.unlinkSync(adoptApplied.project.file);
  fs.renameSync(adopted.project.file, path.join(root, 'moved.org'));
  assert.equal(listProjectNotes(root).projects.find(p => p.id === adopted.project.id).relativePath, 'moved.org');
  fs.writeFileSync(path.join(root, 'duplicate.org'), adopted.content);
  assert.equal(listProjectNotes(root).projects.length, 1);
  assert.equal(listProjectNotes(root).diagnostics.length, 2);
  fs.writeFileSync(path.join(root, 'ordinary.org'), '* Normal note\n#+begin_src org\n#+ORG2_KIND: project\n#+end_src\n');
  fs.writeFileSync(path.join(root, 'broken.org'), '#+ORG2_KIND: project\n');
  assert.equal(listProjectNotes(root).diagnostics.length, 3);
  assert.throws(() => createProjectNote(root, {title: 'Bad', file: '../escape.org'}), /inside/);
  fs.symlinkSync(os.tmpdir(), path.join(root, 'outside'));
  assert.throws(() => createProjectNote(root, {title: 'Bad', file: 'outside/escape.org'}), /inside/);
  assert.throws(() => createProjectNote(root, {title: 'Bad\nInjected'}), /single line/);
  assert.throws(() => updateProjectNote(root, created.project.id, {color: 'invalid'}), /color/);
  const cli = spawnSync(process.execPath, ['dist/cli.js', 'project', 'list', '--dir', root, '--json'], {encoding: 'utf8'});
  assert.equal(cli.status, 0, cli.stderr);
  assert.equal(JSON.parse(cli.stdout).projects.length, 1);
  console.log('OK: project preview/apply, adoption, membership, revision conflicts, discovery, and boundaries');
} finally { fs.rmSync(root, {recursive: true, force: true}); }
