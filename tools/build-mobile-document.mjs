import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

// JavaScriptCore has no filesystem. Parsing receives explicit workflow defaults;
// rendering only needs POSIX basename. Any accidental I/O fails visibly.
const result = await build({
  entryPoints: ["src/mobileDocument.ts"], bundle: true, write: false,
  format: "iife", globalName: "Org2MobileDocument", platform: "browser", target: "safari17",
  plugins: [{ name: "native-runtime-boundary", setup(build) {
    build.onResolve({ filter: /^node:(fs|path)$/ }, args => ({ path: args.path, namespace: "native-boundary" }));
    build.onLoad({ filter: /.*/, namespace: "native-boundary" }, args => ({ contents:
      `const unavailable = () => { throw new Error("Filesystem access is unavailable in the mobile document runtime"); };
       export default new Proxy(${args.path === "node:path" ? '{ basename: value => value.replace(/\\/+$/, "").split("/").pop() || "" }' : '{}'}, { get: (target, key) => target[key] ?? unavailable });`
    }));
  }}]
});
const output = "apps/ios/Org2Mobile/Org2Mobile/Org2MobileDocument.js";
const text = "// Generated by tools/build-mobile-document.mjs. Do not edit.\n" + result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) throw new Error("Mobile document runtime is stale; run npm run build:mobile-document");
} else writeFileSync(output, text);
